//! What the Rust reports of the salted guest, as Lean data the Lean side checks its assembled
//! program against (`tests/LeanVMTests/SaltedGuest/Manifest.lean`): the log size, the code length,
//! the function count, the instructions of each opcode, and the seed of the exporter's salt
//! (`Seed::of_salt`, the Lean `seedOfSalt`), which hashes the stacked bytecode and so pins every
//! instruction.

use super::*;
use leanvm_core::cpu::Op;

/// The counts of `XOR`, `MUL`, `SET`, `DEREF`, `JUMP`, `KECCAK` in the whole padded bytecode.
pub fn opcode_counts(prog: &[Op]) -> [usize; 6] {
    let mut n = [0; 6];
    for op in prog {
        n[match op {
            Op::Xor { .. } => 0,
            Op::Mul { .. } => 1,
            Op::Set { .. } => 2,
            Op::Deref { .. } => 3,
            Op::Jump { .. } => 4,
            Op::Keccak { .. } => 5,
        }] += 1;
    }
    n
}

/// A 32-byte string as four little-endian lanes, a Lean `Digest`.
pub fn lanes(bytes: &[u8; 32]) -> String {
    let lanes: Vec<String> = (0..4)
        .map(|i| format!("0x{:016x}", u64::from_le_bytes(bytes[8 * i..8 * i + 8].try_into().unwrap())))
        .collect();
    format!("#v[{}]", lanes.join(", "))
}

pub fn file() -> File {
    let g = guest();
    let counts = opcode_counts(g.prog());
    let text = format!(
        "/-\n  LeanVMTests.SaltedGuest.Manifest\n\n  Generated by `guest-export` (lean_vm/scripts/guest-export) from leanVM {rev}; do not\n  \
         edit. What the Rust reports of the salted aggregation guest.\n-/\n\n\
         import Statement.Keccak\n\n\
         namespace LeanVMTests.SaltedGuest.Manifest\n\n\
         open LeanVM.Protocol\n\n\
         /-- The leanVM commit the guest was compiled at. -/\ndef leanvmRev : String := {rev:?}\n\n\
         /-- The log of the bytecode size. -/\ndef logSize : Nat := {log}\n\n\
         /-- The compiled functions' instructions. -/\ndef codeLen : Nat := {code}\n\n\
         /-- The compiled functions. -/\ndef functionCount : Nat := {nf}\n\n\
         /-- The instructions of each opcode (`XOR`, `MUL`, `SET`, `DEREF`, `JUMP`, `KECCAK`), the padding included. -/\n\
         def opcodeCounts : List Nat := {counts:?}\n\n\
         /-- The salt of the exported vectors. -/\ndef salt : Digest := {salt}\n\n\
         /-- `Seed::of_salt(salt)`: Keccak-256 of the salt, the version tag and the stacked bytecode. -/\n\
         def seed : Digest := {seed}\n\n\
         end LeanVMTests.SaltedGuest.Manifest\n",
        rev = env!("LEANVM_REV"),
        log = g.prog().len().trailing_zeros(),
        code = g.code_len(),
        nf = g.fn_ranges.len(),
        salt = lanes(&SALT),
        seed = lanes(&seed().to_bytes()),
    );
    File {
        path: "tests/LeanVMTests/SaltedGuest/Manifest.lean".into(),
        text,
    }
}
