"""The salted guest's `level_queries` and `walk_path` walk instances (`WalkLqK*.lean`,
`WalkWpK.lean`), from the deployed ones (`WalkLqOk*.lean`, `WalkWpOk.lean`) by name.

Run from lean_vm/: python3 -I scripts/salted-walks/walkgen.py WORK, WORK the directory holding
`compare.tsv` (`lake env lean --run scripts/salted-walks/Compare.lean WORK`). The modules it
writes are checked by the kernel; they are not trusted.
"""
import sys
from pathlib import Path
LEAN_VM = Path(__file__).resolve().parent.parent.parent
WORK = Path(sys.argv[1])
import re
G = LEAN_VM / 'LeanVM/Guest'
OUT = LEAN_VM / 'LeanVM/SaltedGuest'
cmp = {}
for l in open(WORK / 'compare.tsv'):
    p = l.rstrip('\n').split('\t')
    cmp[p[3]] = int(p[0]) + 1
def hdr(mod, what, imports):
    return f"""/-
  LeanVM.SaltedGuest.{mod}

  Generated by `scripts/salted-walks/walkgen.py`; do not edit.
  {what}
-/

module

{imports}
namespace LeanVM.SaltedGuest.End

open LeanVM.SaltedGuest LeanVM.Guest

open LeanVM.Parameters LeanVM.Semantics LeanVM.SaltedGuest LeanVM.Guest LeanVM.Guest.Core LeanVM.SaltedGuest.Check LeanVM.Guest.Check

@[expose] public section

"""
lq = []
for f in sorted(G.glob('WalkLqOk*.lean')):
    for m in re.finditer(r"/-- `(level_queries__[\w]+)`\. -/\ntheorem lqOk_\d+ : lqOk \(certOf \d+\) (\d+) (\d+) (\d+) (\d+) (\d+) = true", f.read_text()):
        lq.append((cmp[m.group(1)], m.group(1)) + tuple(int(x) for x in m.groups()[1:]))
wp = []
for m in re.finditer(r"/-- `(walk_path__[\w]+)`\. -/\ntheorem walkOk_\d+ : wpOkJ \d+ (\d+) (\d+) = true", (G / 'WalkWpOk.lean').read_text()):
    wp.append((cmp[m.group(1)], m.group(1), int(m.group(2)), int(m.group(3))))
lq.sort(); wp.sort()
chunks = [lq[i:i + 64] for i in range(0, len(lq), 64)]
for k, ch in enumerate(chunks):
    body = "".join(f"/-- `{n}`. -/\ntheorem walk_{j} : CutsKnown {j} :=\n  lq_cutsKnown (by decide) (by decide) (by decide) (by decide) (by decide)\n    (by decide +kernel : lqOk (certOf {j}) {a} {b} {c} {d} {e} = true)\n\n" for j, n, a, b, c, d, e in ch)
    (OUT / f'WalkLqK{k}.lean').write_text(hdr(f'WalkLqK{k}', "The cut obligations of `level_queries`' specializations, from their certificates' decided\n  checks (`lq_cutsKnown`, `lqOk`).", "public import LeanVM.SaltedGuest.WalkKnown\n") + body + "end\nend LeanVM.SaltedGuest.End\n")
body = "".join(f"/-- `{n}`. -/\ntheorem walk_{j} : CutsKnown {j} :=\n  wp_cutsKnown (by decide) (by decide)\n    (by decide +kernel : wpOk (certOf {j}) ({pd} + {cd}) {cd} = true)\n\n" for j, n, pd, cd in wp)
(OUT / 'WalkWpK.lean').write_text(hdr('WalkWpK', "The cut obligations of `walk_path`'s specializations, from their certificates' decided checks\n  (`wp_cutsKnown`, `wpOk`).", "public import LeanVM.SaltedGuest.WalkKnown\n") + body + "end\nend LeanVM.SaltedGuest.End\n")
print(len(lq), len(wp), len(chunks))
