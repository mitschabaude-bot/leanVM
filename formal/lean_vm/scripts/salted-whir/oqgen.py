"""Generate `LeanVM/SaltedGuest/B1/Opening/QueriesBodyK{k}.lean`, `QueriesLoopsK.lean`: the salted
`opening_queries` specializations of the deployed `openingQueriesLoops` and the loop helpers they
call are the salted templates (`oqMainTK`, `oqLoop1TK`, `oqLoop0TK`), by kernel evaluation; the
table of the salted specializations with their loop helpers.

  python3 scripts/salted-whir/oqgen.py
"""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from names import ROOT, SALTED

w = open(os.path.join(ROOT, 'LeanVM/Guest/B1/Opening/Witness.lean')).read()
t = w[w.index('def openingQueriesLoops'):]
t = t[:t.index(']\n')]
rows = re.findall(r'\("([^"]+)", "([^"]+)", ⟨(\d+), (\d+), (\d+), (\d+)⟩, (\d+)\)', t)


def body_text(j):
    for f in sorted(glob.glob(os.path.join(ROOT, 'LeanVM/SaltedGuest/Data/Core*.lean'))):
        s = open(f).read()
        m = re.search(r'^namespace core%d\n(.*?)^end core%d\n' % (j, j), s, re.M | re.S)
        if m:
            return m.group(1)


tab = []
for (n, _, b, I, pd, cd, odd) in rows:
    loop = re.search(r'\.callIf \(\.n \d+\) "(__loop\d+)"', body_text(SALTED[n])).group(1)
    tab.append((n, loop, f'⟨{b}, {I}, {pd}, {cd}⟩', odd, b))
PER = 11
chunks = [tab[i:i + PER] for i in range(0, len(tab), PER)]
out = os.path.join(ROOT, 'LeanVM/SaltedGuest/B1/Opening')
for k, ch in enumerate(chunks):
    s = f"""/-
  LeanVM.SaltedGuest.B1.Opening.QueriesBodyK{k}

  Generated by `scripts/salted-whir/oqgen.py`; do not edit.
  The bodies of a quarter of the salted `opening_queries`' specializations and of their loop
  helpers are the salted templates (kernel evaluation).
-/

module

public import LeanVM.SaltedGuest.B1.Opening.QueriesTK
public import LeanVM.SaltedGuest.CoreData

namespace LeanVM.SaltedGuest.B1

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest LeanVM.Guest.Core LeanVM.Guest.Value LeanVM.Guest.B1
open LeanVM.Protocol.Verifier

@[expose] public section
"""
    for (n, loop, sh, odd, b) in ch:
        jm, jl = SALTED[n], SALTED[loop]
        lt = f'oqLoop1TK {sh} {odd}' if b == '1' else f'oqLoop0TK {sh}'
        s += f"""
set_option maxRecDepth 100000 in
/-- `{n}`. -/
theorem oqBodyK_{jm} : LeanVM.SaltedGuest.Data.core{jm}.body = oqMainTK {sh} {odd} (oqWalkOf {sh}) "{loop}" :=
  stmtsEqb_sound (by decide +kernel)

set_option maxRecDepth 100000 in
/-- `{loop}`, the loop of `{n}`. -/
theorem oqBodyK_{jl} : LeanVM.SaltedGuest.Data.core{jl}.body = {lt} (oqWalkOf {sh}) "{loop}" :=
  stmtsEqb_sound (by decide +kernel)
"""
    s += "\nend\nend LeanVM.SaltedGuest.B1\n"
    open(os.path.join(out, f'QueriesBodyK{k}.lean'), 'w').write(s)
s = """/-
  LeanVM.SaltedGuest.B1.Opening.QueriesLoopsK

  Generated by `scripts/salted-whir/oqgen.py`; do not edit.
  The salted specializations of `opening_queries` with their loop helpers and shapes.
-/

module

public import LeanVM.SaltedGuest.B1.Opening.QueriesTK

namespace LeanVM.SaltedGuest.B1

open LeanVM.Guest.B1

@[expose] public section

/-- The salted specializations with their loop helpers and shapes: `(name, loop, shape, odd)`. -/
def openingQueriesLoopsK : List (String × String × Oq × ℕ) :=
  [""" + ',\n    '.join(f'("{n}", "{loop}", {sh}, {odd})' for (n, loop, sh, odd, b) in tab) + """]

end
end LeanVM.SaltedGuest.B1
"""
open(os.path.join(out, 'QueriesLoopsK.lean'), 'w').write(s)
walk = {(int(pd), int(cd)): SALTED[f'walk_path__L{pd}_L{cd}'] for (n, _, b, I, pd, cd, odd) in rows}
for k, ch in enumerate(chunks):
    s = f"""/-
  LeanVM.SaltedGuest.B1.Opening.QueriesInstK{k}

  Generated by `scripts/salted-whir/oqgen.py`; do not edit.
  A quarter of the salted `opening_queries`' specializations are sound with their queries named.
-/

module

public import LeanVM.SaltedGuest.B1.Opening.QueriesBodyK{k}
public import LeanVM.SaltedGuest.B1.Opening.QueriesMainWK

namespace LeanVM.SaltedGuest.B1

open LeanVM.Parameters LeanVM.Semantics LeanVM.Guest LeanVM.Guest.Core LeanVM.Guest.Value LeanVM.Guest.B1

@[expose] public section
"""
    for (n, loop, sh, odd, b) in ch:
        jm, jl = SALTED[n], SALTED[loop]
        pd, cd = map(int, re.match(r'⟨\d+, \d+, (\d+), (\d+)⟩', sh).groups())
        jw = walk[(pd, cd)]
        if b == '1':
            head = f"oqMain1_sound_wK (s := {sh}) (Or.inl ⟨rfl, rfl⟩) rfl (by decide) (by decide)\n    (hodd := (by decide : {odd} ≤ 1)) (hW := wpFnK_{jw})"
        else:
            head = f"oqMain0_sound_wK (s := {sh}) (Or.inr ⟨rfl, rfl⟩) rfl (by decide) (by decide)\n    (hW := wpFnK_{jw})"
        s += f"""
set_option maxRecDepth 100000 in
/-- `{n}` is sound with its queries named. -/
theorem oqSpecWK_{jm} : opening_queries_sound_w_SpecK "{n}" "{loop}" {sh} {odd} :=
  {head}
    (Program.find?_of_indexOf? (j := {jm}) (by decide +kernel) rfl) rfl oqBodyK_{jm}
    (Program.find?_of_indexOf? (j := {jl}) (by decide +kernel) rfl) rfl oqBodyK_{jl}
"""
    s += "\nend\nend LeanVM.SaltedGuest.B1\n"
    open(os.path.join(out, f'QueriesInstK{k}.lean'), 'w').write(s)
s = """/-
  LeanVM.SaltedGuest.B1.Opening.QueriesAllWK

  Generated by `scripts/salted-whir/oqgen.py`; do not edit.
  Every salted `opening_queries` specialization is sound with its queries named.
-/

module

""" + ''.join(f"public import LeanVM.SaltedGuest.B1.Opening.QueriesInstK{k}\n" for k in range(len(chunks))) + """public import LeanVM.SaltedGuest.B1.Opening.QueriesLoopsK

namespace LeanVM.SaltedGuest.B1

open LeanVM.Guest.B1

@[expose] public section

/-- **Every salted `opening_queries` is sound with its queries named.** -/
theorem opening_queries_all_sound_wK :
    ∀ p ∈ openingQueriesLoopsK, opening_queries_sound_w_SpecK p.1 p.2.1 p.2.2.1 p.2.2.2 :=
""" + ''.join(f"  List.forall_mem_cons.2 ⟨oqSpecWK_{SALTED[n]},\n" for (n, loop, sh, odd, b) in tab) + "  List.forall_mem_nil _" + "⟩" * len(tab) + """

end
end LeanVM.SaltedGuest.B1
"""
open(os.path.join(out, 'QueriesAllWK.lean'), 'w').write(s)
print(len(tab), 'specializations,', len(chunks), 'modules')
