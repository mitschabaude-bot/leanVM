"""Generate `LeanVM/SaltedGuest/B1/Whir/OsSame.lean`: the names of `open_stacked`'s unchanged callees
(the deployed tables `oodPointNamesAll`, `finalMessageNames`, `foldFinalMsgNames`, `lpTable`,
`lrTable`, and four single names) are in the closed set and kept by the renaming, each from its
entry in `Same.closed` and its deployed function, by the kernel's `rfl` (no string compared).

  python3 scripts/salted-whir/samegen.py
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from names import ROOT

pairs = open(os.path.join(ROOT, 'LeanVM/SaltedGuest/Same/Pairs.lean')).read()
closed = []
for b in range(24):
    m = re.search(r'def block%d : List \(String × Nat × Nat\) := \[(.*?)\]\n' % b, pairs, re.S)
    closed += [(n, int(i), int(j)) for n, i, j in re.findall(r'\("([^"]+)", (\d+), (\d+)\)', m.group(1))]
pos = {n: (k, i, j) for k, (n, i, j) in enumerate(closed)}


def names_of(path, defname):
    s = open(os.path.join(ROOT, path)).read()
    i = s.index('def ' + defname)
    j = s.index('\n\n', i)
    return re.findall(r'\("([^"]+)"', s[i:j])


tabs = {
    'ood': names_of('LeanVM/Guest/B1/Opening/Meaning.lean', 'oodPointNames ') +
           names_of('LeanVM/Guest/B1/Opening/OodPointHi.lean', 'oodPointNamesAll'),
    'fm': names_of('LeanVM/Guest/B1/Opening/Meaning.lean', 'finalMessageNames'),
    'ffm': names_of('LeanVM/Guest/B1/Eq/Meaning.lean', 'foldFinalMsgNames'),
    'lp': names_of('LeanVM/Guest/B1/Whir/HelperAll.lean', 'lpTable'),
    'lr': names_of('LeanVM/Guest/B1/Whir/HelperAll.lean', 'lrTable'),
}
tabs['lp'] = [n for n in tabs['lp'] if n.startswith('level_positions')]
tabs['lr'] = [n for n in tabs['lr'] if n.startswith('level_residual')]
single = ['assert_canonical', 'grind_check__L17', 'opening_row_weights__L6_L1',
          'opening_row_weights__L4_L0', 'opening_fold']
need = sorted(set(sum(tabs.values(), []) + single), key=lambda n: pos[n][0])
s = '''/-
  LeanVM.SaltedGuest.B1.Whir.OsSame

  Generated by `scripts/salted-whir/samegen.py`; do not edit.
  `open_stacked`'s unchanged callees are in the closed set and kept by the renaming.
-/

module

public import LeanVM.SaltedGuest.Same
public import LeanVM.Guest.B1.Whir.HelperAll
public import LeanVM.Guest.B1.Opening.OodPointHi
public import LeanVM.Guest.B1.Opening.Meaning
public import LeanVM.Guest.B1.Eq.Meaning

/-!
# `open_stacked`'s unchanged callees

`sameOf`: a name with an entry `(f, i, j)` in `Same.closed` whose deployed function `j` is named `f`
is in the closed set and kept by the renaming (`Same.closed_ok`: the deployed function of a pair
is named by the renaming). The entries and the deployed functions by the kernel's `rfl`; the
tables' statements (`oodSame`, `fmSame`, `ffmSame`, `lpSame`, `lrSame`) from them.
-/

namespace LeanVM.SaltedGuest.B1.Whir

open LeanVM.Guest LeanVM.Guest.Core LeanVM.Guest.B1 LeanVM.Guest.B1.Whir

@[expose] public section

theorem sameOf {k i j : ℕ} {f : String} (hk : Same.closed[k]? = some (f, i, j)) {g : Fn}
    (hg : Guest.coreProgram[j]? = some g) (hn : g.name = f) :
    Same.inS f = true ∧ Same.rho f = f := by
  have hp : (f, i, j) ∈ Same.closed := List.mem_of_getElem? hk
  refine ⟨?_, ?_⟩
  · simp only [Same.inS, List.contains_iff_mem, List.mem_map]
    exact ⟨_, hp, rfl⟩
  · obtain ⟨-, g', -, hg', -, hn', -⟩ := Same.closed_ok _ hp
    rw [hg] at hg'
    cases hg'
    exact hn'.symm.trans hn

set_option maxRecDepth 100000
'''
idx = {}
for n in need:
    k, i, j = pos[n]
    idx[n] = k
    s += f'''
kernel_rfl cl_{k} : Same.closed[{k}]? = some ("{n}", {i}, {j})
kernel_rfl dg_{k} : Guest.coreProgram[{j}]? = some LeanVM.Guest.Data.core{j}
theorem sm_{k} : Same.inS "{n}" = true ∧ Same.rho "{n}" = "{n}" := sameOf cl_{k} dg_{k} rfl
'''
for t, path, d in [('ood', '', 'oodPointNamesAll'), ('fm', '', 'finalMessageNames'),
                   ('ffm', '', 'foldFinalMsgNames'), ('lp', '', 'lpTable'), ('lr', '', 'lrTable')]:
    ns = tabs[t] if t != 'ood' else tabs['ood']
    s += f'\ntheorem {t}Same : ∀ e ∈ {d}, Same.inS e.1 = true ∧ Same.rho e.1 = e.1 :=\n'
    for n in ns:
        s += f'  List.forall_mem_cons.2 ⟨sm_{idx[n]},\n'
    s += '  List.forall_mem_nil _' + '⟩' * len(ns) + '\n'
for n in single:
    s += f'\ntheorem same_{n.replace("__", "_")} : Same.inS "{n}" = true ∧ Same.rho "{n}" = "{n}" := sm_{idx[n]}\n'
s += '\nend\nend LeanVM.SaltedGuest.B1.Whir\n'
open(os.path.join(ROOT, 'LeanVM/SaltedGuest/B1/Whir/OsSame.lean'), 'w').write(s)
print(len(need), 'names', {t: len(v) for t, v in tabs.items()})
