"""Generate `LeanVM/SaltedGuest/B1/Whir/LqData{k}.lean` and `LqDataAll.lean`: every specialization of
the deployed `lqTable` (`Guest/B1/Whir/HelperAll.lean`) is, in the salted core IR, the salted
template `lqBodyK` (found by name, its index checked by the kernel, its body by `stmtsEqb`).

  python3 scripts/salted-whir/lqgen.py
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from names import ROOT, SALTED

PER = 48
src = open(os.path.join(ROOT, 'LeanVM/Guest/B1/Whir/HelperAll.lean')).read()
tab = src[src.index('def lqTable'):]
tab = tab[:tab.index(']\n')]
rows = re.findall(r'\("([^"]+)", (\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\)', tab)
out = os.path.join(ROOT, 'LeanVM/SaltedGuest/B1/Whir')
chunks = [rows[i:i + PER] for i in range(0, len(rows), PER)]
HEAD = """/-
  LeanVM.SaltedGuest.B1.Whir.LqData{k}

  Generated by `scripts/salted-whir/lqgen.py`; do not edit.
  Specializations of the salted `level_queries` are its template, by kernel evaluation.
-/

module

public import LeanVM.SaltedGuest.B1.Whir.LqK

namespace LeanVM.SaltedGuest.B1.Whir

open LeanVM.Guest.Core LeanVM.Guest LeanVM.Guest.B1 LeanVM.Guest.B1.Whir

@[expose] public section
"""
for k, ch in enumerate(chunks):
    s = HEAD.format(k=k)
    for (n, *a) in ch:
        j = SALTED[n]
        s += f"""
set_option maxRecDepth 100000 in
/-- `{n}`. -/
theorem lqK_{j} : FnIsK "{n}" (osParams 3) (lqBodyK {' '.join(a)}) :=
  ⟨LeanVM.SaltedGuest.Data.core{j}, Program.find?_of_indexOf? (j := {j}) (by decide +kernel) rfl,
    by decide +kernel, stmtsEqb_sound (by decide +kernel)⟩
"""
    s += "\nend\nend LeanVM.SaltedGuest.B1.Whir\n"
    open(os.path.join(out, f'LqData{k}.lean'), 'w').write(s)
s = """/-
  LeanVM.SaltedGuest.B1.Whir.LqDataAll

  Generated by `scripts/salted-whir/lqgen.py`; do not edit.
  Every specialization of `level_queries` in the deployed table is, in the salted core IR, the
  salted template.
-/

module

public import LeanVM.Guest.B1.Whir.HelperAll
""" + ''.join(f"public import LeanVM.SaltedGuest.B1.Whir.LqData{k}\n" for k in range(len(chunks))) + """
namespace LeanVM.SaltedGuest.B1.Whir

open LeanVM.Guest.Core LeanVM.Guest LeanVM.Guest.B1 LeanVM.Guest.B1.Whir

@[expose] public section

set_option maxRecDepth 100000 in
/-- **The salted `level_queries` specializations are the salted template.** -/
theorem lqTableK_ok : ∀ e ∈ lqTable, FnIsK e.1 (osParams 3)
    (lqBodyK e.2.1 e.2.2.1 e.2.2.2.1 e.2.2.2.2.1 e.2.2.2.2.2.1 e.2.2.2.2.2.2) :=
"""
for (n, *a) in rows:
    s += f"  List.forall_mem_cons.2 ⟨lqK_{SALTED[n]},\n"
s += "  List.forall_mem_nil _" + "⟩" * len(rows) + "\n\nend\nend LeanVM.SaltedGuest.B1.Whir\n"
open(os.path.join(out, 'LqDataAll.lean'), 'w').write(s)
print(len(rows), 'rows,', len(chunks), 'modules')
