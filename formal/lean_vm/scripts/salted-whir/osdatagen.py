"""Generate `LeanVM/SaltedGuest/B1/Whir/OsData{m}.lean` and `OsDataAll.lean` from the deployed
`Guest/B1/Whir/Data{m}.lean`: each size's salted `open_stacked__L{m}` is the deployed template
`osBody (osCfg m)`, its index the salted one.

  python3 scripts/salted-whir/osdatagen.py
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from names import ROOT, SALTED, table

DEP = table('LeanVM/Guest/Data')
out = os.path.join(ROOT, 'LeanVM/SaltedGuest/B1/Whir')
for m in range(11):
    s = open(os.path.join(ROOT, f'LeanVM/Guest/B1/Whir/Data{m}.lean')).read()
    n = f'open_stacked__L{m}'
    d, k = DEP[n], SALTED[n]
    s = s.replace(f'Data.core{d}', f'LeanVM.SaltedGuest.Data.core{k}').replace(f'(j := {d})', f'(j := {k})')
    s = s.replace(f'LeanVM.Guest.B1.Whir.Data{m}', f'LeanVM.SaltedGuest.B1.Whir.OsData{m}')
    s = s.replace('Generated by whir-data-gen.py', 'Generated by `scripts/salted-whir/osdatagen.py`')
    s = s.replace('`open_stacked__L', 'The salted `open_stacked__L')
    s = s.replace('public import LeanVM.Guest.B1.Whir.DataSpec', 'public import LeanVM.SaltedGuest.B1.Whir.LqK')
    s = s.replace('namespace LeanVM.Guest.B1.Whir', 'namespace LeanVM.SaltedGuest.B1.Whir')
    s = s.replace('end LeanVM.Guest.B1.Whir', 'end LeanVM.SaltedGuest.B1.Whir')
    s = s.replace('open LeanVM.Guest.Core LeanVM.Guest', 'open LeanVM.Guest.Core LeanVM.Guest LeanVM.Guest.B1 LeanVM.Guest.B1.Whir')
    s = re.sub(rf'osData_{m}\b', f'osDataK_{m}', s).replace(f'OsData {m}', f'OsDataK {m}')
    s = re.sub(rf'os_run_{m}_', f'osK_run_{m}_', s)
    s = s.replace(f'`osData_{m} : OsData {m}`', f'`osDataK_{m} : OsDataK {m}`')
    assert f'core{k}' in s
    open(os.path.join(out, f'OsData{m}.lean'), 'w').write(s)
a = open(os.path.join(ROOT, 'LeanVM/Guest/B1/Whir/DataAll.lean')).read()
a = a.replace('LeanVM.Guest.B1.Whir.Data', 'LeanVM.SaltedGuest.B1.Whir.OsData').replace('namespace LeanVM.Guest.B1.Whir', 'namespace LeanVM.SaltedGuest.B1.Whir\n\nopen LeanVM.Guest.B1.Whir').replace('end LeanVM.Guest.B1.Whir', 'end LeanVM.SaltedGuest.B1.Whir')
a = a.replace('Every size\'s core IR is its template.', 'Every size\'s salted core IR is its template.').replace('Generated by whir-data-gen.py', 'Generated by `scripts/salted-whir/osdatagen.py`')
a = re.sub(r'osData_(\d+)', r'osDataK_\1', a).replace('osData_all', 'osDataK_all').replace('OsData m', 'OsDataK m')
open(os.path.join(out, 'OsDataAll.lean'), 'w').write(a)
