#!/usr/bin/env python3
"""Write the salted child proof reader's table of `level_queries` dispatches and its kernel checks.

Input: the dispatches of each size and rate (`lake env lean scripts/salted-whir/oscalls.lean`).
Writes `LeanVM/SaltedGuest/Decoder/WhirTables.lean` (`osCallsTabK`: each size and rate's
dispatches as the deployed `OsCall`s of numbers, the salted functions' indices and the salted
`opening_queries` call's cells) and `LeanVM/SaltedGuest/Decoder/WhirTablesCheck/C{k}.lean` (the
table is the template's, a size and rate at a time, `callsOKK_j`).

    python3 -I scripts/salted-whir/osgen.py FILE [--check]
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from names import SALTED

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
OUT = os.path.join(ROOT, 'LeanVM/SaltedGuest/Decoder/WhirTables.lean')
CHK = os.path.join(ROOT, 'LeanVM/SaltedGuest/Decoder/WhirTablesCheck')
HEADER = "Generated by `scripts/salted-whir/osgen.py`; do not edit."
PER = 11  # sizes per check module


def ints(s):
    return [int(x) for x in re.findall(r'\d+', s)]


def main():
    src, check = sys.argv[1], '--check' in sys.argv
    tab = {}
    for line in open(src):
        if not re.match(r'^\d+ ', line):
            continue
        head, args, rets, names, call = [p.strip() for p in line.split('|')]
        h = ints(head)
        j, base, I, pd, cd, odd, N, depth, capd = h
        a = ints(args)
        n = len(a) // 2
        assert a[n:] == [0] * n
        r = ints(rets)
        assert r == list(range(r[0], r[0] + 4))
        lq, fn, loop, walk = names.split()
        qa, qr = [ints(x) for x in re.findall(r'\[[^\]]*\]', call)]
        assert qa[:3] == [4, 45, 0] and qa[4:6] == [1, 2] and qa[6] == qa[3] + 1 and qr == [qa[3] + 2], line
        assert cd == capd
        idx = lambda nm: SALTED[nm] + 1
        tab.setdefault(j, []).append(
            f"⟨{base}, {I}, {pd}, {cd}, {odd}, {N}, {idx(lq)}, {idx(fn)}, {idx(loop)}, {idx(walk)}, "
            f"{depth}, [{', '.join(map(str, a[:n]))}], {r[0]}, {qa[3]}⟩")
    assert sorted(tab) == list(range(44))
    rows = []
    for j in range(44):
        rows.append(f"  -- size {j % 11}, rate {j // 11 + 1}\n  [" + ",\n    ".join(tab[j]) + "]")
    files = {OUT: f'''/-
  LeanVM.SaltedGuest.Decoder.WhirTables

  {HEADER}
-/

module

public import LeanVM.Guest.Fast.WhirTables

/-!
# The salted `open_stacked`'s dispatches, a literal table

Each size and rate's levels' `level_queries` dispatches (`osQCalls`) as the deployed `OsCall`s of
numbers, at the index `(r - 1) * 11 + m`, with the salted functions' indices (the `level_queries`
specialization, its `opening_queries` call, the call's loop helper and `walk_path`) and the salted
call's cells (`OsCall.qargsK`, from `pw`); `WhirTablesCheck.lean` proves it the template's.
-/

namespace LeanVM.SaltedGuest.Decoder

open LeanVM.Guest.Fast

@[expose] public section

/-- The salted `opening_queries` call's argument cells in its `level_queries` callee. -/
def _root_.LeanVM.Guest.Fast.OsCall.qargsK (c : OsCall) : List Nat := [4, 45, 0, c.pw, 1, 2, c.pw + 1]

/-- Each size and rate's salted `level_queries` dispatches, at `(r - 1) * 11 + m`. -/
def osCallsTabK : List (List OsCall) := [
''' + ",\n".join(rows) + ''']

end

end LeanVM.SaltedGuest.Decoder
'''}
    for k in range(0, 44, PER):
        thms = "\n".join(f"theorem callsOKK_{j} : CallsOKK {j} := by unfold CallsOKK; decide +kernel\n"
                         for j in range(k, min(44, k + PER)))
        files[os.path.join(CHK, f'C{k // PER}.lean')] = f'''/-
  LeanVM.SaltedGuest.Decoder.WhirTablesCheck.C{k // PER}

  {HEADER}
-/

module

public import LeanVM.SaltedGuest.Decoder.WhirTablesDefs

/-! # The salted dispatches of sizes and rates `{k}` to `{min(44, k + PER) - 1}`, checked by the kernel -/

namespace LeanVM.SaltedGuest.Decoder

@[expose] public section

set_option maxRecDepth 100000

{thms}
end

end LeanVM.SaltedGuest.Decoder
'''
    imports = "\n".join(f"public import LeanVM.SaltedGuest.Decoder.WhirTablesCheck.C{k}"
                         for k in range((44 + PER - 1) // PER))
    cases = "\n".join(f"  | {j}, _ => callsOKK_{j}" for j in range(44))
    files[CHK + '.lean'] = f'''/-
  LeanVM.SaltedGuest.Decoder.WhirTablesCheck

  {HEADER}
-/

module

{imports}

/-! # The salted dispatches' table is the template's, at every size and rate -/

namespace LeanVM.SaltedGuest.Decoder

@[expose] public section

/-- **Every size and rate's salted dispatches are the table's.** -/
theorem callsOKK : ∀ j < 44, CallsOKK j
{cases}
  | _ + 44, h => absurd h (by omega)

end

end LeanVM.SaltedGuest.Decoder
'''
    stale = []
    for p, t in files.items():
        if check:
            if not os.path.exists(p) or open(p).read() != t:
                stale.append(p)
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, 'w').write(t)
    if stale:
        sys.exit('stale: ' + ' '.join(stale) + ': run scripts/salted-whir/osgen.py')


main()
